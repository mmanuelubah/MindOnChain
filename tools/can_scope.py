"""Draw the home page oscilloscope: one real CAN 2.0A frame, as CAN-H and CAN-L.

The frame is the OBD-II request every scan tool sends for engine speed:
ID 0x7DF (functional broadcast), DLC 8, data 02 01 0C 00 00 00 00 00
("2 bytes follow, service 01 current data, PID 0C engine RPM", zero padded).

Bits, CRC-15 and bit stuffing follow ISO 11898-1, so a technician reading the
trace sees a frame that would decode. Output is a Hugo partial.

    python3 tools/can_scope.py > layouts/partials/can-scope.html
"""

FRAME_ID = 0x7DF
DATA = [0x02, 0x01, 0x0C, 0x00, 0x00, 0x00, 0x00, 0x00]


def bits(value, width):
    return [(value >> (width - 1 - i)) & 1 for i in range(width)]


def crc15(stream):
    crc = 0
    for b in stream:
        nxt = b ^ ((crc >> 14) & 1)
        crc = (crc << 1) & 0x7FFF
        if nxt:
            crc ^= 0x4599
    return crc


# Unstuffed fields up to the end of the data field, then the CRC over them.
fields = [
    ("SOF", [0]),
    ("ID 7DF", bits(FRAME_ID, 11)),
    ("RTR IDE r0", [0, 0, 0]),
    ("DLC 8", bits(len(DATA), 4)),
    ("DATA 02 01 0C 00 00 00 00 00", [b for byte in DATA for b in bits(byte, 8)]),
]
crc = crc15([b for _, f in fields for b in f])
fields.append(("CRC", bits(crc, 15)))

# Bit stuffing: after five equal bits, insert the opposite bit. Applies SOF..CRC.
stuffed, spans, run_bit, run_len = [], [], None, 0
for name, fb in fields:
    start = len(stuffed)
    for b in fb:
        stuffed.append(b)
        run_len = run_len + 1 if b == run_bit else 1
        run_bit = b
        if run_len == 5:
            stuffed.append(1 - b)
            run_bit, run_len = 1 - b, 1
    spans.append((name, start, len(stuffed)))

tail = [("DEL", [1]), ("ACK", [0]), ("DEL", [1]), ("EOF", [1] * 7)]
for name, fb in tail:
    start = len(stuffed)
    stuffed += fb
    spans.append((name, start, len(stuffed)))

IDLE = 3
levels = [1] * IDLE + stuffed + [1] * IDLE          # 1 = recessive, 0 = dominant
spans = [(n, s + IDLE, e + IDLE) for n, s, e in spans]

# Geometry (SVG user units)
X0, X1 = 40, 960
STEP = (X1 - X0) / len(levels)
H_REC, H_DOM = 128, 92      # CAN-H: 2.5 V rest, 3.5 V dominant (1 V/div = 36)
L_REC, L_DOM = 236, 272     # CAN-L: 2.5 V rest, 1.5 V dominant
EDGE = 1.6                  # rise/fall, so edges read as a real trace


def trace(rec, dom):
    y = lambda lv: rec if lv else dom
    pts = [f"M{X0:.1f} {y(levels[0])}"]
    for i in range(1, len(levels)):
        x = X0 + i * STEP
        if levels[i] != levels[i - 1]:
            pts.append(f"L{x - EDGE:.1f} {y(levels[i - 1])}L{x + EDGE:.1f} {y(levels[i])}")
    pts.append(f"L{X1:.1f} {y(levels[-1])}")
    return "".join(pts)


grid = []
for i in range(11):
    x = X0 + i * (X1 - X0) / 10
    grid.append(f'<path d="M{x:.1f} 56V308"/>')
for j in range(8):
    y = 56 + j * 36
    grid.append(f'<path d="M{X0} {y}H{X1}"/>')

labels, short = [], {"DATA 02 01 0C 00 00 00 00 00": "DATA", "RTR IDE r0": "CTRL", "DLC 8": "DLC", "ID 7DF": "ID"}
for name, s, e in spans:
    if name == "DEL":
        continue
    x0, x1 = X0 + s * STEP, X0 + e * STEP
    labels.append(f'<path d="M{x0 + 1:.1f} 322v8H{x1 - 1:.1f}v-8"/>')
    text = name if (x1 - x0) > len(name) * 7.5 else short.get(name, name)
    if (x1 - x0) > len(text) * 7:
        labels.append(f'<text x="{(x0 + x1) / 2:.1f}" y="348" text-anchor="middle">{text}</text>')

decode = " ".join(f"{b:02X}" for b in DATA)
